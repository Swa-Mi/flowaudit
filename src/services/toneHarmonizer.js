// Tone Harmonizer & Voice-to-Diff Engine for Flow Audit

const BLUNT_TRIGGERS = [
  { raw: /ugh/gi, replacement: '' },
  { raw: /completely awful|terrible|horrible|sucks|stupid/gi, replacement: 'sub-optimal under load' },
  { raw: /why are we doing/gi, replacement: 'we could consider' },
  { raw: /it's gonna die in prod|blow up prod/gi, replacement: 'may introduce latency variance in production' },
  { raw: /who wrote this/gi, replacement: 'in this current iteration' },
  { raw: /rip this out/gi, replacement: 'refactor this section' },
  { raw: /broken/gi, replacement: 'unhandled edge case' }
];

export function analyzeToneMetrics(rawTranscript) {
  let toxicityCount = 0;
  const lower = rawTranscript.toLowerCase();

  const bluntWords = ['awful', 'terrible', 'sucks', 'stupid', 'die', 'blow up', 'rip', 'ugh', 'crap', 'broken'];
  bluntWords.forEach(word => {
    if (lower.includes(word)) toxicityCount++;
  });

  const basePoliteness = Math.max(15, Math.min(85, 80 - toxicityCount * 22));
  const rawPoliteness = Math.min(95, basePoliteness);
  const harmonizedPoliteness = 97;

  return {
    rawPoliteness,
    harmonizedPoliteness,
    toxicityFilteredCount: toxicityCount,
    actionability: 100,
    clarityScore: 98,
    isBlunt: toxicityCount > 0 || lower.includes('bottleneck') || lower.includes('ugh')
  };
}

export function generateHarmonizedComment(rawTranscript, toneKey = 'diplomatic', scenario) {
  // If the scenario has pre-configured tone outputs, pull from the tone set
  if (scenario?.tones?.[toneKey]) {
    const toneData = scenario.tones[toneKey];
    return {
      title: toneData.title,
      description: toneData.description,
      comment: toneData.comment,
      suggestedCode: scenario.suggestedReplacement,
      metrics: toneData.scoreMetrics
    };
  }

  // Dynamic generative fallback for custom input
  let cleaned = rawTranscript;
  BLUNT_TRIGGERS.forEach(({ raw, replacement }) => {
    cleaned = cleaned.replace(raw, replacement);
  });

  const tonesMap = {
    diplomatic: {
      title: "Diplomatic & Mentoring",
      description: "Respectful, encouraging, explaining the technical 'why' with positive reinforcement.",
      prefix: "### 🔍 Constructive Review Suggestion\n\nThanks for working on this! To ensure optimal performance and robustness, here is a suggested enhancement based on your review:",
      metrics: { politeness: 98, clarity: 95, actionability: 100, constructiveness: 98 }
    },
    direct: {
      title: "Direct & Concise",
      description: "High-signal, to-the-point review comment favored in fast-moving engineering teams.",
      prefix: "### ⚡ Code Review Optimization\n\n- Key Focus: Performance & safety enhancement.\n- Suggested changes applied below:",
      metrics: { politeness: 88, clarity: 98, actionability: 100, constructiveness: 92 }
    },
    architect: {
      title: "Senior Staff Architect",
      description: "Focuses on operational resilience, systemic invariants, and long-term maintainability.",
      prefix: "### 🏛️ Architecture & Reliability Review\n\nEvaluating for system-level invariants, algorithmic boundary conditions, and maintainability:",
      metrics: { politeness: 92, clarity: 96, actionability: 98, constructiveness: 96 }
    },
    socratic: {
      title: "Socratic & Collaborative",
      description: "Guides the author through curious inquiry while providing the concrete solution.",
      prefix: "### 💡 Collaborative Suggestion\n\nWhat do you think about streamlining this section to optimize memory and execution time? Here's an approach to consider:",
      metrics: { politeness: 96, clarity: 93, actionability: 96, constructiveness: 97 }
    }
  };

  const selectedTone = tonesMap[toneKey] || tonesMap.diplomatic;
  const comment = `${selectedTone.prefix}\n\n${cleaned.trim()}`;

  return {
    title: selectedTone.title,
    description: selectedTone.description,
    comment,
    suggestedCode: scenario?.suggestedReplacement || '// Refactored implementation',
    metrics: selectedTone.metrics
  };
}

export function formatGitHubSuggestionMarkdown(comment, suggestedCode, startLine, endLine, filename) {
  return `${comment}

\`\`\`suggestion
${suggestedCode}
\`\`\`

---
*Generated by [Flow Audit](https://github.com/flowaudit/companion) Desktop Companion • Anchored to \`${filename}\` (Lines ${startLine}–${endLine})*`;
}
